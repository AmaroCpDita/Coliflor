export const ALL_OBJECTS: WorldObjectDef[] = [
  ...TREES,
  ...PLANTS,
  ...DECORATIONS,
  ...GARDEN_COLLECTION,
  ...FOREST_COLLECTION,
].map((object) => ({ ...object, requiredLevel: OBJECT_UNLOCKS[object.id].level }));

/** Look up any object definition by ID */
export function getObjectDef(id: string): WorldObjectDef | undefined {
  return ALL_OBJECTS.find((o) => o.id === (LEGACY_OBJECT_IDS[id] || id));
}

// Compatibility for existing inventories, rewards and placements.
const LEGACY_OBJECT_IDS: Record<string, string> = {
  oak_seed: 'oak_tree',
  pine_seed: 'pine_tree',
  birch_seed: 'birch_tree',
  willow_seed: 'willow_tree',
  palm_seed: 'willow_tree',
  stone_bench: 'wooden_bench',
  golden_seed: 'firefly_bush',
};

export function getPlacementDef(id: string): WorldObjectDef | undefined {
  return getObjectDef(id);
}

/** Get all objects of a specific type */
export function getObjectsByType(type: WorldObjectDef['type']): WorldObjectDef[] {
  return ALL_OBJECTS.filter((o) => o.type === type);
}

/** Get all placeable objects available at a given level */
export function getPlaceableObjectsForLevel(level: number): WorldObjectDef[] {
  return ALL_OBJECTS.filter((o) => o.placeable && o.requiredLevel <= level);
}

/** Get all objects available in a biome */
export function getObjectsForBiome(biomeId: string): WorldObjectDef[] {
  return ALL_OBJECTS.filter((o) => !o.biomes || o.biomes.includes(biomeId));
}
