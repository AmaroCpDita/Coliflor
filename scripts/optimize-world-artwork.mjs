import sharp from 'sharp';
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import path from 'node:path';

// Keep PNG masters intact; only these delivery copies are requested by the app.
const registry = await readFile('src/features/our-world/data/assets.ts', 'utf8');
const sprites = [
  ...new Set([...registry.matchAll(/\/assets\/world\/[^'"\s]+\.png/g)].map((match) => match[0])),
];
const landscapes = [
  '/assets/world/garden-empty-v3.png',
  '/assets/world/garden-night-v1.png',
  '/assets/world/secret-garden-day-v1.png',
  '/assets/world/secret-garden-night-v1.png',
  '/assets/world/secret-beach-day-v1.png',
  '/assets/world/secret-beach-night-v1.png',
  '/assets/world/magical-glade-day-v1.png',
  '/assets/world/magical-glade-night-v1.png',
  '/assets/world/snowy-mountain-day-v1.png',
  '/assets/world/snowy-mountain-night-v1.png',
];
await mkdir('public/assets/world/optimized', { recursive: true });
const manifest = {};
let originalBytes = 0,
  deliveryBytes = 0,
  thumbnailBytes = 0;
for (const source of [...sprites, ...landscapes]) {
  const input = 'public' + source;
  const name = path.basename(source, '.png');
  const delivery = `/assets/world/optimized/${name}.webp`;
  const landscape = landscapes.includes(source);
  const newBiome = /\/(?:secret-garden|secret-beach|magical-glade|snowy-mountain)-/.test(source);
  const size = newBiome
    ? { width: 840, height: 1500 }
    : landscape
      ? { width: 1200, height: 1920 }
      : { width: 768, height: 768 };
  const info = await sharp(input)
    .resize({ ...size, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: newBiome ? 70 : 86, alphaQuality: 100, effort: 6 })
    .toFile('public' + delivery);
  const metadata = await sharp(input).metadata();
  const entry = {
    source: delivery,
    originalSource: source,
    width: info.width,
    height: info.height,
    originalWidth: metadata.width,
    originalHeight: metadata.height,
  };
  if (!landscape) {
    entry.thumbnail = `/assets/world/optimized/${name}-thumb.webp`;
    const thumb = await sharp(input)
      .resize({ width: 128, height: 128, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 82, alphaQuality: 100, effort: 6 })
      .toFile('public' + entry.thumbnail);
    thumbnailBytes += thumb.size;
  }
  manifest[source] = entry;
  originalBytes += (await stat(input)).size;
  deliveryBytes += info.size;
}
await writeFile(
  'src/features/our-world/data/optimized-artwork.ts',
  '// Generated by npm run optimize:world. Keep the PNG masters.\nexport const optimizedArtwork: Record<string, { source: string; originalSource: string; thumbnail?: string; width: number; height: number; originalWidth: number; originalHeight: number }> = ' +
    JSON.stringify(manifest, null, 2) +
    ';\n',
);
console.log(
  JSON.stringify(
    {
      images: Object.keys(manifest).length,
      originalBytes,
      deliveryBytes,
      thumbnailBytes,
      reductionPercent: Math.round((1 - deliveryBytes / originalBytes) * 100),
    },
    null,
    2,
  ),
);
