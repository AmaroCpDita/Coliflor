import { readFileSync, writeFileSync } from 'node:fs';
const read = name => readFileSync(`supabase/migrations/${name}`, 'utf8');
const fn = (source, name) => source.match(new RegExp(`CREATE OR REPLACE FUNCTION public\\.${name}\\([\\s\\S]*?\\n\\$\\$;`))[0];
const old = read('018_world_daily_boost.sql');
const forest = read('017_forest_chapter.sql');
const sql = readFileSync('supabase/calendar-xp-core.sql', 'utf8');
const grant = fn(old, 'grant_world_xp').replace('v_multiplier := public.world_daily_xp_multiplier(p_couple_id);', 'v_multiplier := 1;').replace('p_xp := LEAST(5 * v_multiplier, GREATEST(0, v_budget - v_spent));', 'p_xp := 0;');
const daily = fn(old, 'claim_world_daily').replace('v_xp INT := 15;', 'v_xp INT := 0;');
const multiplier = `CREATE OR REPLACE FUNCTION public.world_daily_xp_multiplier(p_couple_id UUID)
RETURNS INT LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM couples WHERE id=p_couple_id AND auth.uid() IN (user1_id,user2_id)) THEN RAISE EXCEPTION 'Not authorized'; END IF;
  RETURN 1;
END;
$$;`;
const progress = fn(forest, 'get_forest_progress').replace("'target_days',56", "'target_days',0").replace('v_days>=56 AND ', '').replaceAll('LEAST(7,v_one)', 'LEAST(3,v_one)').replaceAll('LEAST(7,v_two)', 'LEAST(3,v_two)').replace("'target',14", "'target',6");
const complete = fn(forest, 'complete_forest').replace('los 56 días de visita y el nivel 21', 'el nivel 21');
writeFileSync('supabase/migrations/021_world_calendar_xp.sql', `-- Apply after 020. Generated by scripts/build-calendar-xp-migration.mjs.
BEGIN;
${sql}
${multiplier}
${grant}
${daily}
${progress}
${complete}
COMMIT;
`);
const reset = `
-- Admin-only scoped integration launch. Keeps every non-world feature untouched.
CREATE OR REPLACE FUNCTION public.admin_launch_calendar_world(p_couple_id UUID,p_reset_key TEXT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_result JSONB; v_started TIMESTAMPTZ;
BEGIN
  v_result := admin_reset_world_for_launch(p_couple_id,p_reset_key);
  IF COALESCE((v_result->>'already_reset')::BOOLEAN,false) THEN RETURN v_result; END IF;
  v_started := clock_timestamp();
  UPDATE world_states SET calendar_xp_started_at=v_started,
    calendar_xp_started_on=(v_started AT TIME ZONE 'America/Santiago')::DATE
    WHERE couple_id=p_couple_id;
  RETURN v_result || jsonb_build_object('xp_started_at',v_started);
END;
$$;
REVOKE ALL ON FUNCTION public.admin_launch_calendar_world(UUID,TEXT) FROM PUBLIC,anon,authenticated;
`;
writeFileSync('supabase/launch-calendar-world-from-zero.sql', readFileSync('supabase/migrations/021_world_calendar_xp.sql','utf8').replace(/COMMIT;\s*$/, '')+reset+`
SELECT public.admin_launch_calendar_world('7b8edae0-65da-44b7-a9b9-8073ecdd607e'::UUID,'amaro-javiera-calendar-integration-v1') AS result;
NOTIFY pgrst, 'reload schema';
COMMIT;
`);
