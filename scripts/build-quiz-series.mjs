import { readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ configFile: false, cacheDir: 'tmp.local/quiz-series-vite-cache',
  server: { middlewareMode: true }, appType: 'custom', optimizeDeps: { noDiscovery: true } });
try {
  const { getDailyQuiz, THEMED_QUIZZES } = await server.ssrLoadModule('/src/lib/quizBank.ts');
  const { NEW_QUIZZES, QUIZ_SERIES_START } = await server.ssrLoadModule('/src/lib/quizSeries.ts');
  const normalize = text => text.trim().toLocaleLowerCase('es').replace(/\s+/g, ' ');
  const oldQuestions = new Set(THEMED_QUIZZES.flatMap(quiz => quiz.questions.map(q => normalize(q.question))));
  const seen = new Set();
  const quizzes = [getDailyQuiz('2026-10-03')];
  for (let day = 0; day < NEW_QUIZZES.length; day++) {
    const date = new Date(Date.parse(`${QUIZ_SERIES_START}T00:00:00Z`) + day * 86400000).toISOString().slice(0, 10);
    const quiz = getDailyQuiz(date);
    if (quiz.questions.length !== 5) throw new Error(`Incomplete quiz: ${date}`);
    for (const q of quiz.questions) {
      const key = normalize(q.question);
      if (oldQuestions.has(key) || seen.has(key)) throw new Error(`Repeated question: ${q.question}`);
      if (q.options.length !== 4 || new Set(q.options).size !== 4) throw new Error(`Invalid options: ${q.question}`);
      seen.add(key);
    }
    quizzes.push(quiz);
  }
  const literal = value => "'" + value.replace(/'/g, "''") + "'";
  const rows = quizzes.map(q => `  (${literal(q.id.replace('daily-quiz-', ''))},${literal(JSON.stringify(q))}::JSONB)`);
  writeFileSync('supabase/migrations/023_quiz_series.sql',
    '-- Generated by scripts/build-quiz-series.mjs. Append new dates; updates published questions.\n' +
    'BEGIN;\nINSERT INTO public.daily_quizzes(quiz_date,payload) VALUES\n' + rows.join(',\n') +
    '\nON CONFLICT(quiz_date) DO UPDATE SET payload = EXCLUDED.payload;\nCOMMIT;\n');
  const withoutTransaction = sql => sql.replace(/^BEGIN;\s*$/gm, '').replace(/^COMMIT;\s*$/gm, '');
  writeFileSync('supabase/activate-starter-and-quizzes.sql',
    '-- Run this entire file in the Supabase SQL Editor AFTER migration 021.\n' +
    '-- Adds the missing starter pack and home, daily quiz XP and a non-repeating series.\n' +
    '-- Preserves existing progress and objects. Replay is safe. No world reset.\nBEGIN;\n' +
    withoutTransaction(readFileSync('supabase/migrations/022_world_starter_and_quiz.sql','utf8')) + '\n' +
    withoutTransaction(readFileSync('supabase/migrations/023_quiz_series.sql','utf8')) + '\n' +
    withoutTransaction(readFileSync('supabase/migrations/024_world_level_gifts.sql','utf8')) + '\nCOMMIT;\n');
  console.log(`${NEW_QUIZZES.length} new quizzes, ${seen.size} unique new questions; preserves today's quiz.`);
} finally { await server.close(); }
