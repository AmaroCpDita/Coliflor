import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
// Mechanically extract the generated 4x2 atlas; keep masters unchanged.
const frameSize = 256;
const manifest = {};
await mkdir('public/assets/world/optimized', { recursive: true });
for (const pet of ['max', 'abi']) {
  const source = `public/assets/world/${pet}-animation-sheet-v1.png`;
  const meta = await sharp(source).metadata();
  if (!meta.hasAlpha) throw new Error(`${pet}: transparent atlas required`);
  const tiles = [];
  for (let index = 0; index < 8; index++) {
    const col = index % 4, row = Math.floor(index / 4);
    const left = Math.round(col * meta.width / 4), top = Math.round(row * meta.height / 2);
    const width = Math.round((col + 1) * meta.width / 4) - left;
    const height = Math.round((row + 1) * meta.height / 2) - top;
    const input = await sharp(source).extract({ left, top, width, height })
      .resize(224, 224, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .extend({ top: 16, bottom: 16, left: 16, right: 16, background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .png().toBuffer();
    tiles.push({ input, left: index * frameSize, top: 0 });
  }
  const output = `/assets/world/optimized/${pet}-animation-v1.webp`;
  const info = await sharp({ create: { width: frameSize * 8, height: frameSize, channels: 4,
    background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite(tiles)
    .webp({ quality: 88, alphaQuality: 100, effort: 4 }).toFile('public' + output);
  manifest[pet] = { source: output, frames: 8, frameSize, bytes: info.size };
}
await writeFile('src/features/our-world/data/companion-animation.ts',
  '// Generated by node scripts/build-companion-animation.mjs.\nexport const COMPANION_ANIMATION = ' + JSON.stringify(manifest, null, 2) + ' as const;\n');
console.log(JSON.stringify(manifest));
