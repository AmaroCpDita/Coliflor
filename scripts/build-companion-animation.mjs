import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { format } from 'prettier';
// Mechanically extract the generated 4x2 atlas; keep masters unchanged.
const frameSize = 256;
const manifest = {};
await mkdir('public/assets/world/optimized', { recursive: true });
async function keepMainSubject(input) {
  const { data, info } = await sharp(input).raw().toBuffer({ resolveWithObject: true });
  const pixelCount = info.width * info.height;
  const seen = new Uint8Array(pixelCount);
  let largest = [];
  for (let start = 0; start < pixelCount; start++) {
    if (seen[start] || data[start * 4 + 3] < 12) continue;
    const component = [start];
    seen[start] = 1;
    for (let head = 0; head < component.length; head++) {
      const pixel = component[head];
      const x = pixel % info.width;
      const y = Math.floor(pixel / info.width);
      for (let dy = -1; dy <= 1; dy++)
        for (let dx = -1; dx <= 1; dx++) {
          if (
            (!dx && !dy) ||
            x + dx < 0 ||
            x + dx >= info.width ||
            y + dy < 0 ||
            y + dy >= info.height
          )
            continue;
          const neighbor = pixel + dy * info.width + dx;
          if (seen[neighbor] || data[neighbor * 4 + 3] < 12) continue;
          seen[neighbor] = 1;
          component.push(neighbor);
        }
    }
    if (component.length > largest.length) largest = component;
  }
  const keep = new Uint8Array(pixelCount);
  for (const pixel of largest) keep[pixel] = 1;
  for (let pixel = 0; pixel < pixelCount; pixel++) if (!keep[pixel]) data[pixel * 4 + 3] = 0;
  return sharp(data, { raw: { width: info.width, height: info.height, channels: 4 } })
    .png()
    .toBuffer();
}
async function buildSheet(source, output, crops = {}, clean = false) {
  const meta = await sharp(source).metadata();
  if (!meta.hasAlpha || meta.width !== 1774 || meta.height !== 887)
    throw new Error(`${source}: 1774x887 transparent atlas required`);
  const tiles = [];
  for (let index = 0; index < 8; index++) {
    const col = index % 4,
      row = Math.floor(index / 4);
    const defaultLeft = Math.round((col * meta.width) / 4),
      top = Math.round((row * meta.height) / 2);
    const [left, right] = crops[index] || [defaultLeft, Math.round(((col + 1) * meta.width) / 4)];
    const width = right - left;
    const height = Math.round(((row + 1) * meta.height) / 2) - top;
    const input = await sharp(source)
      .extract({ left, top, width, height })
      .resize(224, 224, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .extend({
        top: 16,
        bottom: 16,
        left: 16,
        right: 16,
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .png()
      .toBuffer();
    tiles.push({
      input: clean ? await keepMainSubject(input) : input,
      left: index * frameSize,
      top: 0,
    });
  }
  const info = await sharp({
    create: {
      width: frameSize * 8,
      height: frameSize,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite(tiles)
    .webp({ quality: 88, alphaQuality: 100, effort: 4 })
    .toFile('public' + output);
  return info.size;
}
for (const pet of ['max', 'abi']) {
  const version = pet === 'max' ? 'v2' : 'v1';
  const source = `/assets/world/optimized/${pet}-animation-${version}.webp`;
  const actionSource = `/assets/world/optimized/${pet}-actions-v1.webp`;
  const bytes = await buildSheet(
    `public/assets/world/${pet}-animation-sheet-${version}.png`,
    source,
  );
  // Generated action poses are framed slightly wider than the original cells.
  const actionCrops =
    pet === 'max'
      ? {
          0: [0, 510],
          1: [500, 890],
          2: [885, 1325],
          3: [1320, 1774],
          4: [0, 510],
          5: [430, 935],
          6: [915, 1340],
          7: [1305, 1774],
        }
      : {
          0: [0, 485],
          1: [480, 925],
          2: [920, 1350],
          3: [1340, 1774],
          4: [0, 500],
          5: [470, 930],
          6: [910, 1350],
          7: [1305, 1774],
        };
  const actionBytes = await buildSheet(
    `public/assets/world/${pet}-actions-sheet-v1.png`,
    actionSource,
    actionCrops,
    true,
  );
  manifest[pet] = { source, actionSource, frames: 8, frameSize, bytes, actionBytes };
}
const source =
  '// Generated by node scripts/build-companion-animation.mjs.\n' +
  'export const COMPANION_ANIMATION = ' +
  JSON.stringify(manifest, null, 2) +
  ' as const;\n';
await writeFile(
  'src/features/our-world/data/companion-animation.ts',
  await format(source, { parser: 'typescript', singleQuote: true }),
);
